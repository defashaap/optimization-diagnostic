def comp_label(cid, parsed_config):
    """Human-readable label for a component, e.g. 'turbine c1' or 'pump c3'."""
    comp = parsed_config["components"].get(cid, {})
    ctype = comp.get("type", "component")
    return f"{ctype} {cid}"


def res_label(rid, parsed_config):
    """Human-readable label for a reservoir, e.g. 'reservoir r1'."""
    return f"reservoir {rid}"


def build_iis_constraint_interpretation(parsed_config):
    """
    Build the interpretation dictionary dynamically from config.
    Keys are constraint names as they appear in the Pyomo model.
    """
    interp = {}
    res_ids = sorted(parsed_config["reservoirs"].keys())
    comp_ids = sorted(parsed_config["comp_ids"])
    active_ids = sorted(parsed_config["active_comps"])
    spill_ids = sorted(parsed_config["spills"])

    def wrap_iis_entry(binding_type, interpretation, trigger_risk):
        return {
            "type_of_binding": binding_type,
            "interpretation": interpretation,
            "triggering_forced_constraints": trigger_risk,
        }

    for rid in res_ids:
        rl = res_label(rid, parsed_config)
        interp[f"soft_low_{rid}"] = wrap_iis_entry(
            "lower bound (>=)",
            f"{rl} level must stay above a minimum threshold",
            f"Forced generation or other forced outflows may draw {rl} below the allowable minimum",
        )
        interp[f"soft_high_{rid}"] = wrap_iis_entry(
            "upper bound (<=)",
            f"{rl} level must stay below a maximum threshold",
            f"Forced pumping or other volume-retaining decisions may raise {rl} above the allowable maximum",
        )

    for cid in comp_ids:
        cl = comp_label(cid, parsed_config)
        comp = parsed_config["components"].get(cid, {})
        interp[f"q_upper_{cid}"] = wrap_iis_entry(
            "upper bound (<=)",
            f"{cl} flow cannot exceed its maximum capacity; if the unit is OFF, flow is forced to zero",
            f"Forcing {cl} ON may create a flow pattern that exceeds the allowable maximum",
        )
        if comp.get("type") != "spill":
            interp[f"q_min_on_{cid}"] = wrap_iis_entry(
                "lower bound (>=)",
                f"when {cl} is ON, it must operate above a minimum stable flow",
                f"Forcing {cl} ON when the system cannot supply the minimum required flow can create infeasibility",
            )

    for cid in active_ids:
        cl = comp_label(cid, parsed_config)
        comp = parsed_config["components"][cid]
        if comp["type"] == "turbine":
            trigger_risk = f"Forced {cl} operation may imply flow/head combinations outside the feasible generation region"
            interp[f"approx_{cid}"] = wrap_iis_entry(
                "upper bound (<=)",
                f"power generated by {cl} must remain within the feasible operating region defined by flow and head",
                trigger_risk,
            )
            interp[f"turbine_plane_{cid}"] = wrap_iis_entry(
                "upper bound (<=)",
                f"power generated by {cl} must remain within the feasible operating region defined by flow and head",
                trigger_risk,
            )
        else:
            trigger_risk = f"Forced {cl} operation may imply flow/head combinations outside the feasible pumping region"
            interp[f"approx_{cid}"] = wrap_iis_entry(
                "lower bound (>=)",
                f"{cl} power consumption must remain within the feasible operating region defined by flow and head",
                trigger_risk,
            )
            interp[f"pump_plane_{cid}"] = wrap_iis_entry(
                "lower bound (>=)",
                f"{cl} power consumption must remain within the feasible operating region defined by flow and head",
                trigger_risk,
            )

    for cid in active_ids:
        cl = comp_label(cid, parsed_config)
        interp[f"P_link_up_mode_{cid}"] = wrap_iis_entry(
            "upper bound (<=)",
            f"if {cl} is OFF, power is forced to zero; if ON, power is capped by its mode-specific upper bound",
            f"Forced {cl} operation may push actual power outside the mode-specific upper power limit",
        )
        interp[f"P_link_low_mode_{cid}"] = wrap_iis_entry(
            "lower bound (>=)",
            f"if {cl} is ON, power must stay above its mode-specific lower bound; if OFF, power is forced to zero",
            f"Forced {cl} operation may push actual power below the mode-specific lower power limit",
        )
        interp[f"P_link_up_aux_{cid}"] = wrap_iis_entry(
            "upper bound (<=)",
            f"links {cl} actual power to its auxiliary power under the ON/OFF mode logic",
            f"Forced {cl} operation may drive power above the auxiliary envelope",
        )
        interp[f"P_link_low_aux_{cid}"] = wrap_iis_entry(
            "lower bound (>=)",
            f"links {cl} actual power to its auxiliary power under the ON/OFF mode logic",
            f"Forced {cl} operation may drive power below the auxiliary envelope",
        )

    interp["exclusive_constraints"] = wrap_iis_entry(
        "upper bound (<=)",
        "certain mutually exclusive units cannot be ON at the same hour",
        "Forcing two mutually exclusive units ON simultaneously can create a direct conflict",
    )
    interp["exclusive_const"] = wrap_iis_entry(
        "upper bound (<=)",
        "certain mutually exclusive units cannot be ON at the same hour",
        "Forcing two mutually exclusive units ON simultaneously can create a direct conflict",
    )
    interp["upper_exclusive"] = wrap_iis_entry(
        "upper bound (<=)",
        "the upper turbine and pump cannot both be ON simultaneously",
        "Forcing both upper turbine and pump modes ON simultaneously can create a direct conflict",
    )

    for sid in spill_ids:
        cl = comp_label(sid, parsed_config)
        head_name = "weir_head_trigger" if len(spill_ids) == 1 else f"weir_head_trigger_{sid}"
        flow_name = "weir_qgen_trigger" if len(spill_ids) == 1 else f"weir_qgen_trigger_{sid}"
        interp[head_name] = wrap_iis_entry(
            "lower bound (>=)",
            f"{cl} can only operate when hydraulic trigger conditions are met",
            f"Forcing {cl} activation when trigger conditions are not satisfied, or forcing it OFF when conditions require activation, can create infeasibility",
        )
        interp[flow_name] = wrap_iis_entry(
            "lower bound (>=)",
            f"{cl} can only operate when hydraulic trigger conditions are met",
            f"Forcing {cl} activation when trigger conditions are not satisfied, or forcing it OFF when conditions require activation, can create infeasibility",
        )
        interp[f"head_trigger_{sid}"] = wrap_iis_entry(
            "lower bound (>=)",
            f"{cl} can only operate when hydraulic trigger conditions are met",
            f"Forcing {cl} activation when trigger conditions are not satisfied, or forcing it OFF when conditions require activation, can create infeasibility",
        )
        interp[f"flow_trigger_{sid}"] = wrap_iis_entry(
            "lower bound (>=)",
            f"{cl} can only operate when hydraulic trigger conditions are met",
            f"Forcing {cl} activation when trigger conditions are not satisfied, or forcing it OFF when conditions require activation, can create infeasibility",
        )

    interp["water_balance"] = wrap_iis_entry(
        "equality (=)",
        "reservoir storage condition must satisfy mass balance rule over time",
        "Consecutive forced generation, pumping, or spill decisions may create flow patterns that cannot satisfy mass balance",
    )
    interp["head_eq"] = wrap_iis_entry(
        "equality (=)",
        "reservoir head is determined by reservoir volume",
        "Forced operation may drive reservoir volume to values that imply infeasible head values",
    )
    interp["init_storage"] = wrap_iis_entry(
        "equality (=)",
        "reservoir volume at t=0 is fixed to the configured initial storage",
        "Forcing units connected to the reservoir to be ON at the first time step may cause contradiction in the model",
    )
    interp["init_head"] = wrap_iis_entry(
        "equality (=)",
        "reservoir head/water level at t=0 is fixed to the configured initial water level",
        "Forcing units connected to the reservoir to be ON at the first time step may cause contradiction in the model",
    )
    interp["init_flow"] = wrap_iis_entry(
        "equality (=)",
        "unit flow at t=0 is fixed to the configured initial flow",
        "Forcing a unit ON when initial flow is fixed to zero can create infeasibility",
    )
    interp["init_constraints"] = wrap_iis_entry(
        "equality (=)",
        "initial storage, head, and flow values are fixed at t=0",
        "Forcing units connected to a reservoir to be ON at the first time step may cause a contradiction",
    )
    interp["init_cond"] = wrap_iis_entry(
        "equality (=)",
        "initial storage, head, and flow values are fixed at t=0",
        "Forcing units connected to a reservoir to be ON at the first time step may cause a contradiction",
    )
    interp["keep_p1"] = wrap_iis_entry(
        "equality (=)",
        "keeps phase-1 minimum safety violation fixed during phase-2 optimization",
        "Keeping a phase-1 lock can conflict with later forced adjustments if the original slack is exhausted",
    )

    return interp


